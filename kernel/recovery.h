/* PrismOS — 回復モード
 *
 * 起動時に回復モードに入る方法は 2 つ:
 *   1. 起動直後に R キーを押す (キーボードまたはシリアル)。
 *      kmain が割り込み許可の直後に recovery_key_check() で
 *      約 2 秒だけ待つ。
 *   2. シェルで `recovery` と打つ。ディスクに印を付けて再起動
 *      し、次の起動で回復モードに入る (印は 1 回だけ有効)。
 *
 * 回復モードはログインの後に開く (暗号化されたファイルがある
 * 場合は PIN で復号してから)。画面はまだ無いため、メニューは
 * シリアルに出す。
 *
 * メニュー (仕様の 4 つの選択肢 + 通常起動 / 再起動):
 *   1) データを残して修復 — 組み込みファイルだけを正しい
 *      中身に戻す。ユーザーのファイルは触らない。
 *   2) 復元ポイントから復元 — スナップショットを書き戻す。
 *   3) 初期化 — ディスクを初期化し、組み込みファイルだけにする。
 *   4) 前のバージョンをダウンロードして壊れたファイルだけ修復
 *      — 更新サーバの前の版のマニフェストと比べ、ハッシュが
 *      違う組み込みファイルだけを取ってきて直す。
 *   5) 通常起動へ進む
 *   6) 再起動
 */
#ifndef PRISM_RECOVERY_H
#define PRISM_RECOVERY_H

/* 起動時に R キーが押されたかどうかを調べる。kmain から
 * 割り込み許可の直後に呼ぶ。押されていれば 1。 */
int recovery_key_check(void);

/* 今回の起動で回復モードに入るかどうか。R キーか、ディスクの
 * 印のどちらかで決まる。 */
int recovery_requested(void);

/* 回復モードのメニューを出す。「通常起動へ進む」が選ばれるまで
 * 戻らない。再起動が選ばれた場合は戻らない。 */
void recovery_run(void);

#endif /* PRISM_RECOVERY_H */
