static int is_vowel(char c) {
    return c == 'a' || c == 'i' || c == 'u' || c == 'e' ||
           c == 'o';
}
static int is_consonant(char c) {
    return c >= 'a' && c <= 'z' && !is_vowel(c) && c != 'n';
}

void ime_romaji_to_kana(const char *romaji, char *out,
                        size_t cap) {
    size_t n = 0;
    size_t i = 0;
    if (cap == 0) {
        return;
    }
    out[0] = '\0';
    /* 先読みは終端 NUL の先を読まない (監査 F11)。 */
    size_t rlen = strlen(romaji);
#define ROMA_AT(k) ((k) < rlen ? romaji[k] : '\0')
    while (romaji[i] != '\0') {
        /* 促音: 同じ子音の重なり、または tch。 */
        if (is_consonant(romaji[i]) && ROMA_AT(i + 1) == romaji[i] &&
            romaji[i] != 'x') {
            if (n + 3 < cap) {
                memcpy(out + n, "っ", 3);
                n += 3;
                out[n] = '\0';
            }
            i++;
            continue;
        }
        if (romaji[i] == 't' && ROMA_AT(i + 1) == 'c' &&
            ROMA_AT(i + 2) == 'h') {
            if (n + 3 < cap) {
                memcpy(out + n, "っ", 3);
                n += 3;
                out[n] = '\0';
            }
            i++;
            continue;
        }
        /* 撥音: nn は次が母音/y なら ん+な行、それ以外は
         * ん で両方消費。n' も ん。n+子音/語末も ん。 */
        if (romaji[i] == 'n') {
            char nx = ROMA_AT(i + 1);
            if (nx == '\'') {
                if (n + 3 < cap) {
                    memcpy(out + n, "ん", 3);
                    n += 3;
                    out[n] = '\0';
                }
                i += 2;
                continue;
            }
            if (nx == 'n') {
                char nx2 = ROMA_AT(i + 2);
                if (n + 3 < cap) {
                    memcpy(out + n, "ん", 3);
                    n += 3;
                    out[n] = '\0';
                }
                i += (is_vowel(nx2) || nx2 == 'y') ? 1 : 2;
                continue;
            }
            if (nx == '\0' || !is_vowel(nx)) {
                if (nx != 'y') {
                    if (n + 3 < cap) {
                        memcpy(out + n, "ん", 3);
                        n += 3;
                        out[n] = '\0';
                    }
                    i += 1;
                    continue;
                }
            }
        }
        /* 最長一致で音節を探す。 */
        int matched = 0;
        for (int t = 0; roma_table[t].roma != NULL; t++) {
            size_t rl = strlen(roma_table[t].roma);
            if (strncmp(romaji + i, roma_table[t].roma, rl) == 0) {
                size_t kl = strlen(roma_table[t].kana);
                if (n + kl < cap) {
                    memcpy(out + n, roma_table[t].kana, kl);
                    n += kl;
                    out[n] = '\0';
                }
                i += rl;
                matched = 1;
                break;
            }
        }
        if (!matched) {
            /* 変換できない文字はそのまま残す (未確定表示)。 */
            if (n + 1 < cap) {
                out[n++] = romaji[i];
                out[n] = '\0';
            }
            i++;
        }
    }
#undef ROMA_AT
}

