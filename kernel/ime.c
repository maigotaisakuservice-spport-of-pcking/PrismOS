int ime_lookup(const char *kana, const char **candidates,
               int max) {
    for (int i = 0; ime_dict[i].reading != NULL; i++) {
        if (strcmp(ime_dict[i].reading, kana) == 0) {
            int n = 0;
            while (n < max && ime_dict[i].cand[n] != NULL) {
                candidates[n] = ime_dict[i].cand[n];
                n++;
            }
            return n;
        }
    }
    return 0;
}

/* ひらがな→カタカナ変換 (候補の 1 つとして使う)。 */
static void to_katakana(const char *in, char *out, size_t cap) {
    size_t n = 0;
    size_t i = 0;
    size_t len = strlen(in);
    if (cap == 0) {
        return;
    }
    while (i < len) {
        uint8_t b0 = (uint8_t)in[i];
        if (b0 >= 0xE0 && i + 2 < len) {
            uint32_t cp = ((uint32_t)(b0 & 0x0F) << 12) |
                          ((uint32_t)((uint8_t)in[i + 1] & 0x3F)
                           << 6) |
                          (uint32_t)((uint8_t)in[i + 2] & 0x3F);
            if (cp >= 0x3041 && cp <= 0x3096) {
                cp += 0x60;
                if (n + 3 >= cap) {
                    break;
                }
                out[n++] = (char)0xE3;
                out[n++] = (char)(0x80 | ((cp >> 6) & 0x3F));
                out[n++] = (char)(0x80 | (cp & 0x3F));
                i += 3;
                continue;
            }
            if (n + 3 >= cap) {
                break;
            }
            out[n++] = in[i++];
            out[n++] = in[i++];
            out[n++] = in[i++];
            continue;
        }
        if (n + 1 >= cap) {
            break;
        }
        out[n++] = in[i++];
    }
    out[n] = '\0';
}

/* ---- 状態機械 ---- */
#define IME_ROMA_CAP 48
#define IME_KANA_CAP 160

static int g_ime_on;
static char g_roma[IME_ROMA_CAP];
static char g_kana[IME_KANA_CAP];
static const char *g_cands[5];
static char g_kata[IME_KANA_CAP];
static int g_ncand;
static int g_cand_idx;
static int g_converted;
static char g_display[IME_KANA_CAP + 8];

void ime_reset(void) {
    g_ime_on = 0;
    g_roma[0] = '\0';
    g_kana[0] = '\0';
    g_ncand = 0;
    g_cand_idx = 0;
    g_converted = 0;
    g_display[0] = '\0';
}

int ime_toggle(void) {
    g_ime_on = !g_ime_on;
    g_roma[0] = '\0';
    g_kana[0] = '\0';
    g_ncand = 0;
    g_converted = 0;
    g_display[0] = '\0';
    return g_ime_on;
}

int ime_on(void) {
    return g_ime_on;
}

int ime_active(void) {
    return g_roma[0] != '\0';
}

static void refresh_display(void) {
    if (g_converted && g_ncand > 0) {
        strncpy(g_display, g_cands[g_cand_idx],
                sizeof(g_display) - 1);
        g_display[sizeof(g_display) - 1] = '\0';
    } else {
        ime_romaji_to_kana(g_roma, g_kana, sizeof(g_kana));
        strncpy(g_display, g_kana, sizeof(g_display) - 1);
        g_display[sizeof(g_display) - 1] = '\0';
    }
}

const char *ime_display(void) {
    refresh_display();
    return g_display;
}

int ime_candidate_count(void) {
    return g_converted ? g_ncand : 0;
}

int ime_candidate_index(void) {
    return g_cand_idx;
}

static void start_conversion(void) {
    ime_romaji_to_kana(g_roma, g_kana, sizeof(g_kana));
    /* 末尾に残ったローマ字 (未確定の子音) は変換対象から
     * 外す: かな部分だけで辞書を引く。 */
    g_ncand = ime_lookup(g_kana, g_cands, 4);
    to_katakana(g_kana, g_kata, sizeof(g_kata));
    if (g_ncand < 5) {
        g_cands[g_ncand++] = g_kata;
    }
    if (g_ncand < 5) {
        g_cands[g_ncand++] = g_kana;
    }
    g_converted = 1;
    g_cand_idx = 0;
}

int ime_feed(int c, char *out, size_t cap) {
    if (!g_ime_on) {
        return 0;
    }
    if (c == 0x1B) { /* 取消 */
        g_roma[0] = '\0';
        g_converted = 0;
        g_ncand = 0;
        g_display[0] = '\0';
        return 0;
    }
    if (c == '\b' || c == 0x7F) {
        if (g_converted) {
            g_converted = 0; /* 変換を戻す */
            g_ncand = 0;
        } else if (g_roma[0] != '\0') {
            g_roma[strlen(g_roma) - 1] = '\0';
        }
        refresh_display();
        return 0;
    }
    if (c == ' ') {
        if (g_roma[0] == '\0') {
            return 0; /* 通常の空白として呼び出し側へ */
        }
        if (!g_converted) {
            start_conversion();
        } else {
            g_cand_idx = (g_cand_idx + 1) % g_ncand;
        }
        refresh_display();
        return 0;
    }
    if (c == '\n' || c == '\r') {
        if (g_roma[0] == '\0') {
            return 0; /* 通常の改行として呼び出し側へ */
        }
        refresh_display();
        if (cap > 0) {
            strncpy(out, g_display, cap - 1);
            out[cap - 1] = '\0';
        }
        g_roma[0] = '\0';
        g_converted = 0;
        g_ncand = 0;
        g_display[0] = '\0';
        return 1;
    }
    if (c >= 'a' && c <= 'z') {
        if (g_converted) {
            /* 変換済みの後ろに打ち始めたら、まず現在の
             * 候補を確定してから新しい読みを始める。 */
            if (cap > 0) {
                refresh_display();
                strncpy(out, g_display, cap - 1);
                out[cap - 1] = '\0';
            }
            g_roma[0] = (char)c;
            g_roma[1] = '\0';
            g_converted = 0;
            g_ncand = 0;
            refresh_display();
            return 1;
        }
        size_t n = strlen(g_roma);
        if (n + 1 < sizeof(g_roma)) {
            g_roma[n] = (char)c;
            g_roma[n + 1] = '\0';
        }
        refresh_display();
        return 0;
    }
    return 0;
}
