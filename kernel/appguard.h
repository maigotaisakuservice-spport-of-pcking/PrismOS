/* PrismOS — 内蔵アプリのフォルト封じ込め (appguard)。
 *
 * 内蔵デスクトップアプリはカーネル内 (リング 0) で動く
 * ため、アプリのバグがそのままカーネルの停止になる。
 * プロセス分離 (専用ページテーブル + リング 3) は
 * デスクトップのアプリモデル (単一アドレス空間・直接の
 * フレームバッファ描画) を作り替えないと届かないので、
 * ここでは到達可能な最強の封じ込めを提供する:
 * アプリの描画・入力ディスパッチを appguard_enter() で
 * 武装し、その最中に例外が起きたら例外ハンドラが
 * appguard_bail() でディスパッチ地点へ戻す。デスクトップ
 * 側はアプリを閉じて通知し、カーネルは生き続ける。
 *
 * 限界 (正直に): アプリが共有構造 (設定や VFS) を更新
 * している最中に落ちた場合、その書きかけは残りうる。
 * 封じ込めは「アプリの描画・入力処理中のフォルトで
 * カーネル全体が止まらない」ことを保証するもので、
 * メモリ保護ではない。完全な分離は互換ゲスト
 * (サンドボックス) だけが持つ。 */
#ifndef PRISM_APPGUARD_H
#define PRISM_APPGUARD_H

/* 武装する。0 = 通常復帰、1 = フォルトから戻ってきた。 */
int appguard_enter(void);
/* 武装を解く (正常終了時)。 */
void appguard_leave(void);
/* 武装中なら 1。 */
int appguard_armed(void);
/* 例外ハンドラから呼ぶ。武装地点へ戻り、戻らない。 */
void appguard_bail(void);

#endif /* PRISM_APPGUARD_H */
