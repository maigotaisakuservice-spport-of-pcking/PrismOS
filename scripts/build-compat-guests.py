#!/usr/bin/env python3
"""PrismOS 互換レイヤーの実証ゲストを作る。

compat/*.s (手書きアセンブリ) をホストの as/ld で組み立て、
実行ファイル (ELF64) にして shell/sample_compat.h に C の
バイト列として書き出す。VFS の組み込みファイルとして
カーネルに入り、`run <名前>.elf` で動かせる。

リンクは `ld -N` (ページ境界に詰めない) で行う。普通に
リンクするとセクションの配置だけで 8KB を超え、VFS の
1 ファイル 4096 バイトの上限に入らないため。-N なら
1 本 1KB 未満に収まる。

使い方:
    python3 scripts/build-compat-guests.py
        compat/*.s を build/compat/ に組み立て、
        shell/sample_compat.h を書き出す。

生成物はコミットする (shell/sample_video_pv1.h と同じ扱い)。
手で編集しないこと。再生成するときはこのスクリプトを使う。
"""

import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
COMPAT_DIR = os.path.join(ROOT, "compat")
BUILD_DIR = os.path.join(ROOT, "build", "compat")
HEADER = os.path.join(ROOT, "shell", "sample_compat.h")

# (ファイル名, ソース, C の配列名)
GUESTS = [
    ("hello.elf", "hello.s", "compat_guest_hello"),
    ("calc.elf", "calc.s", "compat_guest_calc"),
    ("cat.elf", "cat.s", "compat_guest_cat"),
    ("unsup.elf", "unsup.s", "compat_guest_unsup"),
    ("evil.elf", "evil.s", "compat_guest_evil"),
    ("loop.elf", "loop.s", "compat_guest_loop"),
    ("cp.elf", "cp.s", "compat_guest_cp"),
    ("wc.elf", "wc.s", "compat_guest_wc"),
    ("gfxdemo.elf", "gfxdemo.s", "compat_guest_gfxdemo"),
    ("netdemo.elf", "netdemo.s", "compat_guest_netdemo"),
]

MAX_FILE_SIZE = 16384  # VFS の 1 ファイル上限


def build_one(name, src, out_elf):
    src_path = os.path.join(COMPAT_DIR, src)
    obj_path = out_elf + ".o"
    for cmd in (
        ["as", "--64", "-o", obj_path, src_path],
        ["ld", "-o", out_elf, "-N", "-Ttext=0x400000", "-e", "_start",
         "-s", obj_path],
    ):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print("FAILED: %s" % " ".join(cmd))
            print(r.stdout)
            print(r.stderr, file=sys.stderr)
            return None
    with open(out_elf, "rb") as f:
        data = f.read()
    if len(data) > MAX_FILE_SIZE:
        print("FAILED: %s is %d bytes (over the %d limit)"
              % (name, len(data), MAX_FILE_SIZE))
        return None
    print("built %s: %d bytes" % (name, len(data)))
    return data


def emit_header(guests):
    lines = []
    lines.append("/* Generated by scripts/build-compat-guests.py. "
                 "Do not edit by hand; regenerate. */")
    lines.append("#ifndef PRISM_SAMPLE_COMPAT_H")
    lines.append("#define PRISM_SAMPLE_COMPAT_H")
    lines.append("")
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    lines.append("")
    for name, _src, arr, data in guests:
        lines.append("static const uint8_t %s[] = {" % arr)
        for i in range(0, len(data), 16):
            chunk = data[i:i + 16]
            lines.append("    " + ", ".join("0x%02x" % b for b in chunk)
                         + ",")
        lines.append("};")
        lines.append("static const size_t %s_len = %d;" % (arr, len(data)))
        lines.append("")
    lines.append("#endif /* PRISM_SAMPLE_COMPAT_H */")
    lines.append("")
    with open(HEADER, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % HEADER)


def build_dyn():
    """動的リンクの実証ゲスト (共有ライブラリ + PIE 本体)。

    通常の ld リンクで作る (-N は使わない)。大きさは
    VFS の上限 (16KB) に収めるため -s で記号を落とす
    (動的シンボルは残る)。
    """
    lib_src = os.path.join(COMPAT_DIR, "libguest.s")
    lib_obj = os.path.join(BUILD_DIR, "libguest.o")
    lib_out = os.path.join(BUILD_DIR, "libguest.so")
    main_src = os.path.join(COMPAT_DIR, "maindyn.s")
    main_obj = os.path.join(BUILD_DIR, "maindyn.o")
    main_out = os.path.join(BUILD_DIR, "maindyn.elf")
    for cmd in (
        ["as", "--64", "-o", lib_obj, lib_src],
        ["ld", "-shared", "-s", "-o", lib_out, lib_obj],
        ["as", "--64", "-o", main_obj, main_src],
        ["ld", "-pie", "-s", "-o", main_out, main_obj,
         "-L", BUILD_DIR, "-lguest"],
    ):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print("FAILED: %s" % " ".join(cmd))
            print(r.stdout)
            print(r.stderr, file=sys.stderr)
            return None
    out = []
    for name, path, arr in (
            ("libguest.so", lib_out, "compat_guest_libguest"),
            ("maindyn.elf", main_out, "compat_guest_maindyn")):
        with open(path, "rb") as f:
            data = f.read()
        if len(data) > MAX_FILE_SIZE:
            print("FAILED: %s is %d bytes (over the %d limit)"
                  % (name, len(data), MAX_FILE_SIZE))
            return None
        print("built %s: %d bytes" % (name, len(data)))
        out.append((name, os.path.basename(path), arr, data))
    return out


def build_shifted(name, src_name, new_base, arr):
    """hello 系ゲストをリンク後にずらした細工 ELF。

    PT_LOAD の p_vaddr と入口を new_base へ寄せ、ローダの
    アドレス検証 (ユーザー空間の外・スタック衝突) を
    QEMU で回帰確認するためのもの。
    """
    src_path = os.path.join(COMPAT_DIR, src_name)
    out_elf = os.path.join(BUILD_DIR, name)
    obj_path = out_elf + ".o"
    for cmd in (
        ["as", "--64", "-o", obj_path, src_path],
        ["ld", "-o", out_elf, "-N", "-Ttext=0x400000", "-e", "_start",
         "-s", obj_path],
    ):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print("FAILED: %s" % " ".join(cmd))
            print(r.stderr, file=sys.stderr)
            return None
    with open(out_elf, "rb") as f:
        data = bytearray(f.read())
    import struct
    phoff = struct.unpack_from("<Q", data, 32)[0]
    phnum = struct.unpack_from("<H", data, 56)[0]
    first_v = None
    for i in range(phnum):
        off = phoff + i * 56
        ptype = struct.unpack_from("<I", data, off)[0]
        if ptype == 1:
            first_v = struct.unpack_from("<Q", data, off + 16)[0]
            break
    if first_v is None:
        print("FAILED: %s has no PT_LOAD" % name)
        return None
    delta = (new_base - first_v) & 0xFFFFFFFFFFFFFFFF
    entry = struct.unpack_from("<Q", data, 24)[0]
    struct.pack_into("<Q", data, 24,
                     (entry + delta) & 0xFFFFFFFFFFFFFFFF)
    for i in range(phnum):
        off = phoff + i * 56
        ptype = struct.unpack_from("<I", data, off)[0]
        if ptype == 1:
            for field in (16, 24):  # p_vaddr, p_paddr
                v = struct.unpack_from("<Q", data, off + field)[0]
                struct.pack_into("<Q", data, off + field,
                                 (v + delta) & 0xFFFFFFFFFFFFFFFF)
    data = bytes(data)
    if len(data) > MAX_FILE_SIZE:
        print("FAILED: %s is %d bytes" % (name, len(data)))
        return None
    print("built %s: %d bytes (base %#x)" % (name, len(data), new_base))
    return (name, src_name, arr, data)


def main():
    os.makedirs(BUILD_DIR, exist_ok=True)
    built = []
    for name, src, arr in GUESTS:
        out_elf = os.path.join(BUILD_DIR, name)
        data = build_one(name, src, out_elf)
        if data is None:
            return 1
        built.append((name, src, arr, data))
    dyn = build_dyn()
    if dyn is None:
        return 1
    built.extend(dyn)
    for name, base, arr in (
            ("evil2.elf", 0xFFFFFFFF80000000, "compat_guest_evil2"),
            ("evil3.elf", 0x7EFFFFFF8000, "compat_guest_evil3")):
        one = build_shifted(name, "hello.s", base, arr)
        if one is None:
            return 1
        built.append(one)
    emit_header(built)
    return 0


if __name__ == "__main__":
    sys.exit(main())
