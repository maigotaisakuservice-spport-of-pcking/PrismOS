#!/usr/bin/env python3
"""Build the sample loadable driver and emit shell/sample_driver.h.

The package format is a plain ET_REL object; this script compiles
drivers/sample_hello.c and turns the bytes into a C array so the
object ships as a built-in VFS file (sample.drv), the same way the
compat guests ship. Run by hand when the sample changes.
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "drivers", "sample_hello.c")
OBJ = os.path.join(ROOT, "build", "sample_hello.o")
OUT = os.path.join(ROOT, "shell", "sample_driver.h")


def main():
    os.makedirs(os.path.join(ROOT, "build"), exist_ok=True)
    subprocess.run(
        ["gcc", "-c", "-fpie", "-fno-plt", "-fno-stack-protector",
         "-mno-sse", "-mno-mmx", "-mno-80387", "-O2",
         "-o", OBJ, SRC],
        check=True)
    data = open(OBJ, "rb").read()
    lines = []
    for i in range(0, len(data), 12):
        chunk = ", ".join("0x%02x" % b for b in data[i:i + 12])
        lines.append("    " + chunk + ",")
    with open(OUT, "w") as f:
        f.write("/* Generated by scripts/build-sample-driver.py. */\n")
        f.write("#ifndef PRISM_SAMPLE_DRIVER_H\n")
        f.write("#define PRISM_SAMPLE_DRIVER_H\n\n")
        f.write("#include <stddef.h>\n#include <stdint.h>\n\n")
        f.write("static const uint8_t sample_driver_pkg[] = {\n")
        f.write("\n".join(lines))
        f.write("\n};\n")
        f.write("static const size_t sample_driver_pkg_len = %d;\n\n"
                % len(data))
        f.write("#endif\n")
    print("wrote %s (%d bytes)" % (OUT, len(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
