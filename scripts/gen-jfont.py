#!/usr/bin/env python3
"""PrismOS Japanese font generator.

Rasterises the JIS X 0208 repertoire from Noto Sans CJK
(SIL Open Font License 1.1; see assets/NotoSansCJK-LICENSE.txt)
at 16x16 pixels and emits kernel/jfont_data.h:

  PRISM_JFONT_CPS[]   - Unicode codepoints, sorted ascending
  PRISM_JFONT[]       - one 32-byte glyph per codepoint
                        (16 rows x 2 bytes, MSB = leftmost)

The kernel looks glyphs up by codepoint (binary search), so
the table only holds characters the font really has.

Usage: python3 scripts/gen-jfont.py [font-path]
Default font: /usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc
(face index 0 is the Japanese face of the TTC).
"""

import sys

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

DEFAULT_FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc"
OUT_C = "kernel/jfont_data.c"
OUT_H = "kernel/jfont_index.h"
SIZE = 16


def jis_x0208_chars():
    """Yield (unicode_char) for every assigned JIS X 0208 code."""
    for row in range(1, 95):
        for ten in range(1, 95):
            b = bytes([0xA0 + row, 0xA0 + ten])
            try:
                ch = b.decode("euc_jp")
            except UnicodeDecodeError:
                continue
            if len(ch) != 1:
                continue
            # Round-trip guard: the char must encode back to the
            # same two EUC-JP bytes (drops JIS X 0212 fallbacks).
            try:
                if ch.encode("euc_jp") != b:
                    continue
            except UnicodeEncodeError:
                continue
            yield ch


def main():
    font_path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_FONT
    tt = TTFont(font_path, fontNumber=0)
    cmap = tt.getBestCmap()
    pil_font = ImageFont.truetype(font_path, SIZE, index=0)

    glyphs = {}  # codepoint -> 32 bytes
    # JIS X 0208 の外だが必ず要る 2 文字:
    # U+FFFD (代替文字。壊れた UTF-8 の表示先) と
    # U+3000 (全角スペース。字形は空白だが、引けること
    # 自体が全角幅の判定に要る)。
    extra = ["\uFFFD", "\u3000"]
    for ch in list(jis_x0208_chars()) + extra:
        cp = ord(ch)
        if cp not in cmap:
            continue
        img = Image.new("L", (SIZE, SIZE), 0)
        d = ImageDraw.Draw(img)
        # Centre the glyph in the cell. Noto CJK is full-width
        # at this size, so x=0 is right; keep a small y offset
        # so the glyph sits on the same baseline area as text.
        d.text((0, -2), ch, fill=255, font=pil_font)
        px = img.load()
        data = bytearray()
        for y in range(SIZE):
            bits = 0
            for x in range(SIZE):
                bits = (bits << 1) | (1 if px[x, y] >= 128 else 0)
            data.append((bits >> 8) & 0xFF)
            data.append(bits & 0xFF)
        if any(data) or cp == 0x3000:
            glyphs[cp] = bytes(data)

    if 0xFFFD not in glyphs:
        # Noto Sans CJK (face 0) の cmap に U+FFFD が無い。
        # 代替文字の字形は慣例の輪郭矩形を自前で描く
        # (フォントデータではないのでライセンスも無関係)。
        data = bytearray()
        for y in range(SIZE):
            bits = 0
            for x in range(SIZE):
                on = (2 <= x <= 13 and (y == 2 or y == 13)) or \
                     (2 <= y <= 13 and (x == 2 or x == 13))
                bits = (bits << 1) | (1 if on else 0)
            data.append((bits >> 8) & 0xFF)
            data.append(bits & 0xFF)
        glyphs[0xFFFD] = bytes(data)

    cps = sorted(glyphs)
    with open(OUT_C, "w") as f:
        f.write("/* PrismOS - Japanese glyph data (16x16).\n")
        f.write(" *\n")
        f.write(" * Generated by scripts/gen-jfont.py from Noto Sans\n")
        f.write(" * CJK Regular (SIL Open Font License 1.1; the\n")
        f.write(" * license text is in assets/NotoSansCJK-LICENSE.txt).\n")
        f.write(" * Glyph i (32 bytes, 16 rows x 2 bytes, MSB =\n")
        f.write(" * leftmost) belongs to PRISM_JFONT_CPS[i] in\n")
        f.write(" * jfont_index.h. Do not edit by hand. */\n")
        f.write("#include <stdint.h>\n\n")
        f.write("const uint8_t PRISM_JFONT_DATA[%d][32] = {\n"
                % len(cps))
        for cp in cps:
            g = glyphs[cp]
            rows = ", ".join("0x%02X" % b for b in g)
            f.write("    { %s }, /* U+%04X */\n" % (rows, cp))
        f.write("};\n")
    with open(OUT_H, "w") as f:
        f.write("/* PrismOS - Japanese font index.\n")
        f.write(" *\n")
        f.write(" * Generated by scripts/gen-jfont.py from Noto Sans\n")
        f.write(" * CJK Regular (SIL Open Font License 1.1; the\n")
        f.write(" * license text is in assets/NotoSansCJK-LICENSE.txt).\n")
        f.write(" * PRISM_JFONT_CPS[i] is the Unicode codepoint of\n")
        f.write(" * glyph i in jfont_data.c (32 bytes each,\n")
        f.write(" * 16 rows x 2 bytes, MSB = leftmost pixel).\n")
        f.write(" * Do not edit by hand; regenerate instead. */\n")
        f.write("#ifndef PRISM_JFONT_INDEX_H\n")
        f.write("#define PRISM_JFONT_INDEX_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#define PRISM_JFONT_COUNT %d\n\n" % len(cps))
        f.write("extern const uint8_t PRISM_JFONT_DATA[PRISM_JFONT_COUNT]"
                "[32];\n\n")
        f.write("static const uint16_t PRISM_JFONT_CPS[PRISM_JFONT_COUNT]"
                " = {\n")
        for i in range(0, len(cps), 8):
            row = ", ".join("0x%04X" % cp for cp in cps[i:i + 8])
            f.write("    %s,\n" % row)
        f.write("};\n\n#endif /* PRISM_JFONT_INDEX_H */\n")
    print("wrote %s + %s: %d glyphs" % (OUT_C, OUT_H, len(cps)))


if __name__ == "__main__":
    main()
