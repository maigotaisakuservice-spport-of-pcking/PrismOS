#!/usr/bin/env python3
"""PrismOS の PE 実証ゲスト (hello2-pe.exe) を作る。

compat/peguest2.s を as/ld で組み立て (配置は RVA に一致
させたリンカスクリプトで固定)、.text と .idata の中身を
取り出して、PE ヘッダを Python で組み立てた実行ファイル
にする。生成物は shell/sample_pe.h に C のバイト列として
書き出す (生成物はコミットする。手で編集しないこと)。

使い方: python3 scripts/build-pe2-guest.py
"""
import os
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "compat", "peguest2.s")
BUILD_DIR = os.path.join(ROOT, "build", "compat")
HEADER = os.path.join(ROOT, "shell", "sample_pe2.h")
IMAGE_BASE = 0x140000000


def align(v, a):
    return (v + a - 1) // a * a


def build():
    os.makedirs(BUILD_DIR, exist_ok=True)
    obj = os.path.join(BUILD_DIR, "peguest2.o")
    elf = os.path.join(BUILD_DIR, "peguest2.elf")
    lds = os.path.join(BUILD_DIR, "peguest2.ld")
    with open(lds, "w") as f:
        f.write(
            "SECTIONS {\n"
            "  . = 0x140001000;\n"
            "  .text : { *(.text) }\n"
            "  . = 0x140002000;\n"
            "  .idata : { *(.idata) }\n"
            "}\n")
    for cmd in (
        ["as", "--64", "-o", obj, SRC],
        ["ld", "-o", elf, "-T", lds, "-e", "_start", "-s", obj],
    ):
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            print("FAILED: %s" % " ".join(cmd))
            print(r.stdout)
            print(r.stderr, file=sys.stderr)
            return None
    blobs = {}
    for sec in (".text", ".idata"):
        out = os.path.join(BUILD_DIR, "peguest2%s.bin" % sec)
        r = subprocess.run(
            ["objcopy", "-O", "binary", "--only-section=%s" % sec,
             elf, out],
            capture_output=True, text=True)
        if r.returncode != 0:
            print("FAILED: objcopy %s" % sec)
            print(r.stderr, file=sys.stderr)
            return None
        with open(out, "rb") as f:
            blobs[sec] = f.read()
    text = blobs[".text"]
    idata = blobs[".idata"]
    if len(idata) < 0x188:
        print("FAILED: .idata too small (%d bytes)" % len(idata))
        return None

    file_align = 0x200
    text_raw = align(len(text), file_align)
    idata_raw = align(len(idata), file_align)
    headers_size = 0x200
    text_ptr = headers_size
    idata_ptr = text_ptr + text_raw

    # DOS ヘッダ (e_lfanew = 0x80)
    dos = bytearray(0x80)
    dos[0:2] = b"MZ"
    struct.pack_into("<I", dos, 0x3C, 0x80)

    # COFF + オプショナルヘッダ (PE32+)
    opt = bytearray(240)
    struct.pack_into("<H", opt, 0, 0x20B)          # magic
    struct.pack_into("<I", opt, 16, 0x1000)        # entry RVA
    struct.pack_into("<Q", opt, 24, IMAGE_BASE)    # image base
    struct.pack_into("<I", opt, 32, 0x1000)        # section align
    struct.pack_into("<I", opt, 36, file_align)    # file align
    struct.pack_into("<I", opt, 56, 0x3000)        # size of image
    struct.pack_into("<I", opt, 60, headers_size)  # size of headers
    struct.pack_into("<H", opt, 68, 3)             # subsystem console
    struct.pack_into("<I", opt, 108, 16)           # dirs count
    # ディレクトリ 1 = インポート (RVA 0x2000, 40 バイト)
    struct.pack_into("<II", opt, 112 + 8, 0x2000, 40)

    coff = struct.pack("<HHIIIHH", 0x8664, 2, 0, 0, 0, 240, 0x0022)

    def section(name, vsize, vaddr, raw_size, raw_ptr, chars):
        b = bytearray(40)
        b[0:len(name)] = name.encode()
        struct.pack_into("<IIII", b, 8, vsize, vaddr, raw_size,
                         raw_ptr)
        struct.pack_into("<I", b, 36, chars)
        return bytes(b)

    sec_text = section(".text", len(text), 0x1000, text_raw,
                       text_ptr, 0x60000020)
    sec_idata = section(".idata", len(idata), 0x2000, idata_raw,
                        idata_ptr, 0xC0000040)

    pe = bytearray()
    pe += dos
    pe += b"PE\0\0"
    pe += coff
    pe += opt
    pe += sec_text
    pe += sec_idata
    assert len(pe) <= headers_size, len(pe)
    pe += b"\0" * (headers_size - len(pe))
    pe += text
    pe += b"\0" * (text_raw - len(text))
    pe += idata
    pe += b"\0" * (idata_raw - len(idata))
    return bytes(pe)


def main():
    data = build()
    if data is None:
        return 1
    lines = []
    lines.append("/* Generated by scripts/build-pe2-guest.py. "
                 "Do not edit by hand; regenerate. */")
    lines.append("#ifndef PRISM_SAMPLE_PE2_H")
    lines.append("#define PRISM_SAMPLE_PE2_H")
    lines.append("")
    lines.append("#include <stddef.h>")
    lines.append("#include <stdint.h>")
    lines.append("")
    lines.append("static const uint8_t compat_guest_hello_pe2[] = {")
    for i in range(0, len(data), 16):
        chunk = data[i:i + 16]
        lines.append("    " + ", ".join("0x%02x" % b for b in chunk)
                     + ",")
    lines.append("};")
    lines.append("static const size_t compat_guest_hello_pe2_len = %d;"
                 % len(data))
    lines.append("")
    lines.append("#endif /* PRISM_SAMPLE_PE2_H */")
    lines.append("")
    with open(HEADER, "w") as f:
        f.write("\n".join(lines))
    print("built hello2-pe.exe: %d bytes" % len(data))
    print("wrote %s" % HEADER)
    return 0


if __name__ == "__main__":
    sys.exit(main())
