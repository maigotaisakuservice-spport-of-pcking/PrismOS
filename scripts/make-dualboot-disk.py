#!/usr/bin/env python3
"""PrismOS dual-boot disk image builder.

Builds a disk with a boot menu (two systems side by side):
  - MBR with the Limine BIOS bootloader installed,
  - partition 1 (16MB, FAT16, bootable): limine-bios.sys, a menu
    limine.conf (timeout 5), boot/prismos.elf and boot/guest.elf,
  - partition 2 (the rest, type 0x83): an empty PRISMFS file
    system the kernel mounts as its data partition.

The "Guest system" entry is not a product OS: it is the
test stand-in for another system (see kernel/guest_main.c).
Its only job is to prove that the menu really boots the
system you pick, not the one you did not.

P1 is 16MB so a kernel update can hold the old and the new
kernel side by side (about 4.6MB each) while the update runs.
P2 is 16MB (32768 sectors), still well above the 10286 sectors
a snapshot needs.

Layout (sectors, 512 bytes each):
  disk: 32MB = 65536 sectors
  P1: start 2048, size 32768 (16MB)
  P2: start 34816, size 30720 (15MB)
  PRISMFS inside P2: superblock at P2+1, table at P2+2..5,
  data from P2+6.

Usage: python3 scripts/make-dualboot-disk.py [--disk PATH]
  (exit code 0 = done; needs qemu-img, mtools, Limine)
"""

import argparse
import os
import struct
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KERNEL = os.path.join(ROOT, "build", "kernel.elf")
GUEST = os.path.join(ROOT, "build", "guest.elf")
LIMINE_BIN = os.path.join(ROOT, "build", "limine", "limine")
LIMINE_BIOS_SYS = os.path.join(ROOT, "build", "limine", "limine-bios.sys")
DEFAULT_DISK = os.path.join(ROOT, "build", "prism-dualboot-disk.img")
MENU_CONF = os.path.join(ROOT, "build", "dualboot-limine.conf")

DISK_SECTORS = 65536  # 32MB
BOOT_START = 2048
BOOT_SECTORS = 32768  # 16MB
DATA_START = 34816
DATA_SECTORS = DISK_SECTORS - DATA_START  # 30720

# The menu text itself is generated by the Makefile
# (build/dualboot-limine.conf) so the disk builder and the
# dual-boot ISO use exactly the same menu.


class DiskBuildFailure(Exception):
    pass


def run(cmd, what):
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode != 0:
        raise DiskBuildFailure("%s failed: %s%s" % (what, r.stdout, r.stderr))


def main():
    parser = argparse.ArgumentParser(description="PrismOS dual-boot disk builder")
    parser.add_argument("--disk", default=DEFAULT_DISK)
    args = parser.parse_args()
    disk = args.disk
    for path in (KERNEL, GUEST, LIMINE_BIN, LIMINE_BIOS_SYS, MENU_CONF):
        if not os.path.exists(path):
            print("MISSING: %s not found (run `make dualboot-disk` first)" % path)
            return 1

    fat_img = os.path.join(ROOT, "build", "prism-dualboot-fat.img")
    try:
        os.unlink(disk)
    except OSError:
        pass
    try:
        os.unlink(fat_img)
    except OSError:
        pass

    try:
        # 1. Blank 32MB disk.
        run(["qemu-img", "create", "-f", "raw", disk, "32M"], "qemu-img")
        print("disk: created 32MB disk image")

        # 2. FAT16 boot partition image with the bootloader files
        #    and both kernels.
        run(["dd", "if=/dev/zero", "of=" + fat_img, "bs=512",
             "count=%d" % BOOT_SECTORS], "dd (FAT image)")
        run(["mformat", "-i", fat_img, "-T", str(BOOT_SECTORS),
             "-v", "PRISMBOOT", "::"], "mformat")
        run(["mmd", "-i", fat_img, "::/boot"], "mmd /boot")
        run(["mcopy", "-i", fat_img, LIMINE_BIOS_SYS,
             "::/limine-bios.sys"], "mcopy limine-bios.sys")
        run(["mcopy", "-i", fat_img, MENU_CONF,
             "::/limine.conf"], "mcopy limine.conf")
        run(["mcopy", "-i", fat_img, KERNEL,
             "::/boot/prismos.elf"], "mcopy kernel")
        run(["mcopy", "-i", fat_img, GUEST,
             "::/boot/guest.elf"], "mcopy guest kernel")
        print("disk: boot files and guest kernel copied to FAT partition")

        # 3. Copy the FAT image into the disk at the P1 offset.
        run(["dd", "if=" + fat_img, "of=" + disk, "bs=512",
             "seek=%d" % BOOT_START, "conv=notrunc"], "dd (FAT into disk)")

        # 4. MBR partition table + empty PRISMFS in P2.
        with open(disk, "r+b") as f:
            mbr = bytearray(512)
            mbr[446] = 0x80  # P1 bootable
            mbr[446 + 4] = 0x0E  # FAT16 LBA
            struct.pack_into("<I", mbr, 446 + 8, BOOT_START)
            struct.pack_into("<I", mbr, 446 + 12, BOOT_SECTORS)
            mbr[462 + 4] = 0x83  # P2: data partition
            struct.pack_into("<I", mbr, 462 + 8, DATA_START)
            struct.pack_into("<I", mbr, 462 + 12, DATA_SECTORS)
            mbr[510] = 0x55
            mbr[511] = 0xAA
            f.seek(0)
            f.write(mbr)
            sb = bytearray(512)
            sb[0:8] = b"PRISMFS2"
            struct.pack_into("<I", sb, 8, 2)   # version
            struct.pack_into("<I", sb, 12, 0)  # file count
            struct.pack_into("<I", sb, 16, 10)  # data start
            struct.pack_into("<I", sb, 20, 32)  # sectors per file
            struct.pack_into("<I", sb, 24, DATA_SECTORS)
            f.seek((DATA_START + 1) * 512)
            f.write(sb)
            f.seek((DATA_START + 2) * 512)
            f.write(bytes(512 * 8))  # empty file table
        print("disk: MBR and empty file system written")

        # 5. Install the Limine BIOS bootloader into the MBR.
        #    It preserves the partition table (verified below).
        run([LIMINE_BIN, "bios-install", disk], "limine bios-install")

        # 6. Verify: partition table, PRISMFS magic, boot files.
        with open(disk, "rb") as f:
            mbr = f.read(512)
            if mbr[510] != 0x55 or mbr[511] != 0xAA:
                raise DiskBuildFailure("MBR signature lost")
            p1 = mbr[446:462]
            if p1[4] != 0x0E or struct.unpack("<I", p1[8:12])[0] != BOOT_START:
                raise DiskBuildFailure("boot partition lost")
            p2 = mbr[462:478]
            if p2[4] != 0x83 or struct.unpack("<I", p2[8:12])[0] != DATA_START:
                raise DiskBuildFailure("data partition lost")
            f.seek((DATA_START + 1) * 512)
            if f.read(8) != b"PRISMFS2":
                raise DiskBuildFailure("file system magic lost")
        run(["mdir", "-i", "%s@@%d" % (disk, BOOT_START * 512),
             "::/boot"], "mdir (verify boot files)")
        print("DISK BUILD OK: %s" % disk)
        return 0
    except DiskBuildFailure as e:
        print("MISSING: %s" % e)
        return 1
    finally:
        try:
            os.unlink(fat_img)
        except OSError:
            pass


if __name__ == "__main__":
    sys.exit(main())
